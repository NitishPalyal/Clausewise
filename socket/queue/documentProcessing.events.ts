import { Queue, QueueEvents } from "bullmq";
import type { Server } from "socket.io";

import configKeys from "@/config/config.keys";
import { emitToTenant } from "../socket.service";

const QUEUE_NAME = "document-processing";

type DocumentJobData = {
  tenantId: string;
  documentVersionId: string;
};

/**
 * Validates the job data before it is used for event routing.
 */
function isDocumentJobData(value: unknown): value is DocumentJobData {
  if (typeof value !== "object" || value === null) {
    return false;
  }

  const data = value as Record<string, unknown>;

  return (
    typeof data.tenantId === "string" &&
    data.tenantId.length > 0 &&
    typeof data.documentVersionId === "string" &&
    data.documentVersionId.length > 0
  );
}

/**
 * Starts listening to the existing document-processing BullMQ queue.
 *
 * For every relevant job event:
 * 1. Retrieves the original job using its job ID.
 * 2. Validates the job's tenant and document identifiers.
 * 3. Sends the event through the shared Socket.IO service.
 *
 * @param io - The running Socket.IO server instance.
 * @returns A function that gracefully closes the queue connections.
 */
export function startDocumentQueueEvents(io: Server) {
  const connection = {
    host: configKeys.REDIS_HOST,
    port: Number(configKeys.REDIS_PORT || "6379"),
  };

  // Connect to the existing BullMQ queue; this does not create another queue.
  const queue = new Queue(QUEUE_NAME, { connection });

  // Listen for events generated by the worker through Redis.
  const queueEvents = new QueueEvents(QUEUE_NAME, { connection });

  /**
   * Retrieves a job, validates its data, and forwards its event
   * to the appropriate tenant through the shared Socket.IO service.
   */
  async function forwardJobEvent(
    jobId: string,
    eventName: string,
    payload: Record<string, unknown> = {},
  ): Promise<void> {
    const job = await queue.getJob(jobId);

    if (!job) {
      console.warn(`Cannot find BullMQ job: ${jobId}`);
      return;
    }

    if (!isDocumentJobData(job.data)) {
      console.warn(`Invalid document job data: ${jobId}`);
      return;
    }

    const { tenantId, documentVersionId } = job.data;

    emitToTenant(io, tenantId, eventName, {
      jobId,
      documentVersionId,
      ...payload,
    });
  }

  // Fired when the worker starts processing a job.
  queueEvents.on("active", ({ jobId }) => {
    void forwardJobEvent(jobId, "document:processing", {
      status: "processing",
    }).catch(console.error);
  });

  // Fired when the worker reports processing progress.
  queueEvents.on("progress", ({ jobId, data }) => {
    void forwardJobEvent(jobId, "document:progress", {
      progress: data,
    }).catch(console.error);
  });

  // Fired when the worker successfully completes a job.
  queueEvents.on("completed", ({ jobId }) => {
    void forwardJobEvent(jobId, "document:ready", {
      status: "completed",
    }).catch(console.error);
  });

  // Fired when the worker fails a job.
  queueEvents.on("failed", ({ jobId }) => {
    void forwardJobEvent(jobId, "document:failed", {
      status: "failed",
      message: "Document processing failed.",
    }).catch(console.error);
  });

  // Log errors originating from the BullMQ event listener.
  queueEvents.on("error", (error) => {
    console.error("BullMQ QueueEvents error:", error);
  });

  /**
   * Closes both BullMQ connections when the Socket.IO server shuts down.
   */
  return async function stopDocumentQueueEvents(): Promise<void> {
    await queueEvents.close();
    await queue.close();
  };
}
